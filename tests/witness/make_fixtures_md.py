"""Writes docs/evidence/T-07/fixtures.md (+ two sample images) from the synthetic fixtures (T-07 Part A).

Run: ``uv run python -m tests.witness.make_fixtures_md``. Deterministic; no network, no key, no camera.
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(REPO / "hardware" / "gauge")]

import cv2  # noqa: E402

from ring3bridge.witness.dial import find_dial, load_geometry  # noqa: E402
from tests.witness import synth  # noqa: E402
from tests.witness.synth import OFFSET_DEG, Scene  # noqa: E402
from tests.witness.test_fixtures import CHECKS  # noqa: E402
from tests.witness.test_inv_14_witness import CASES  # noqa: E402

OUT = REPO / "docs" / "evidence" / "T-07"


def short(line: str) -> str:
    """The SAM line with each mask payload cut to 12 characters (full payload length shown)."""
    out, rest = [], line
    while "data=" in rest:
        head, _, tail = rest.partition("data=")
        h, w, after = tail.split(",", 2)
        end = after.find("|>", 0)
        nxt = after.find("|>,")
        end = nxt if nxt != -1 else len(after) - 2
        payload = after[:end]
        out.append(f"{head}data={h},{w},{payload[:12]}...[{len(payload)} chars]")
        rest = after[end:]
    out.append(rest)
    return "".join(out)


def row(name, scene, cmd, res) -> str:
    dial = "" if res.dial_mdeg is None else f"{res.dial_mdeg / 1000:.1f}"
    cal = "" if res.calibrated_mdeg is None else f"{res.calibrated_mdeg / 1000:.1f}"
    arms = ", ".join(f"{a:g}" for a in scene.arms_deg) or "none"
    extra = f"marker {scene.cover_marker} covered" if scene.cover_marker is not None else ""
    v = f"{res.verdict}: {res.reason}" + (f" ({res.detail})" if res.detail else "")
    return f"| {name} | {arms} | {scene.quad}/{scene.light} {extra} | {cmd} | {dial} | {cal} | {v} |"


def main() -> None:
    geom = load_geometry()
    tmp = Path(tempfile.mkdtemp())
    cal, pairs = synth.calibrate(geom, tmp)
    lines = [
        "# T-07 Part A synthetic fixtures",
        "",
        "Generated by `uv run python -m tests.witness.make_fixtures_md` from the same code the tests run",
        "(`tests/witness/synth.py`). Gauge rendered at 6 px/mm, SG90-like horn (hub r 3.5 mm, tip r 2 mm, 18 mm)",
        "drawn 7 % enlarged about the camera axis (horn ~27 mm above the paper, camera ~400 mm up), projected into",
        "a 1280x960 frame (`flat`, `mild`, `steep`, `rotated` perspectives), blur, light (`even`, `gradient`,",
        "`dim`), noise, JPEG q88. The fake SAM box is the arm label's bounding box after the *detected* dial warp;",
        "the mask payload is a stand-in (Ascii85 of the box raster; the real encoding is undocumented).",
        f"Simulated mounting offset: dial angle = command + {OFFSET_DEG:g} deg.",
        "",
        "## Calibration (5 commanded angles through the pipeline)",
        "",
        "| command (deg) | measured dial (deg) |",
        "|---|---|",
        *[f"| {c} | {m / 1000:.3f} |" for c, m in pairs],
        "",
        f"`{cal.message()}`",
        "",
        "## Checks after calibration",
        "",
        "| case | arm (deg) | camera | commanded | dial (deg) | calibrated (deg) | result |",
        "|---|---|---|---|---|---|---|",
    ]
    samples = []
    for i, (name, truth, cmd, *_) in enumerate(CHECKS):
        sc = Scene([truth], quad="steep", light="gradient")
        d = tmp / f"c{i}"
        d.mkdir()
        res, _, _, line = synth.run_check(sc, cmd, cal, geom, d)
        lines.append(row(name, sc, cmd, res))
        samples.append((name, line))
    lines += ["", "## INV-14 CAN'T VERIFY cases", "",
              "| case | arm (deg) | camera | commanded | dial (deg) | calibrated (deg) | result |",
              "|---|---|---|---|---|---|---|"]  # fmt: skip
    for i, (name, sc, cmd, c, conf, forced, *_) in enumerate(CASES):
        d = tmp / f"i{i}"
        d.mkdir()
        res, t, _, line = synth.run_check(sc, cmd, c, geom, d, conf=conf, line=forced)
        r = row(name, sc, cmd, res)
        lines.append(r if t.posts else r[:-2] + " (no SAM call) |")
        samples.append((name, line if t.posts else ""))
    lines += ["", "## Recorded-style SAM lines (as returned by the fake transport)", ""]
    for name, line in samples:
        lines.append(f"- **{name}**: " + (f"`{short(line)}`" if line else "(none: no SAM call, or empty line)"))
    lines += ["", "## Samples", "", "`fixture_frame.jpg`: camera frame, steep perspective, gradient light, arm at",
              f"{90 + OFFSET_DEG:g} deg. `fixture_crop.jpg`: the dial crop sent to SAM for that frame.", ""]  # fmt: skip
    (OUT / "fixtures.md").write_text("\n".join(lines))
    frame, _, _ = synth.render(Scene([90 + OFFSET_DEG], quad="steep", light="gradient"))
    cv2.imwrite(str(OUT / "fixture_frame.jpg"), frame, [cv2.IMWRITE_JPEG_QUALITY, 80])
    cv2.imwrite(str(OUT / "fixture_crop.jpg"), find_dial(frame, geom).crop_img, [cv2.IMWRITE_JPEG_QUALITY, 85])


if __name__ == "__main__":
    main()
